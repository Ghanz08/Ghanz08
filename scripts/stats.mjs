// Mengambil data publik dari GitHub dan menggambar assets/stats-{dark,light}.svg.
// Jalan di GitHub Actions (GITHUB_TOKEN) maupun lokal (GH_TOKEN=$(gh auth token)).
import { writeFileSync } from "node:fs";
import { esc, svg, themes } from "./theme.mjs";

const LOGIN = process.env.GH_LOGIN || "Ghanz08";
const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
if (!token) throw new Error("GH_TOKEN atau GITHUB_TOKEN belum diisi");

const query = `query($login:String!){ user(login:$login){
  repositories(ownerAffiliations:OWNER, isFork:false, privacy:PUBLIC, first:100){ totalCount
    nodes{ languages(first:8, orderBy:{field:SIZE,direction:DESC}){ edges{ size node{ name color } } } } }
  contributionsCollection{ totalCommitContributions totalPullRequestContributions
    contributionCalendar{ totalContributions weeks{ contributionDays{ contributionCount } } } } } }`;

const res = await fetch("https://api.github.com/graphql", {
  method: "POST",
  headers: { Authorization: `bearer ${token}`, "Content-Type": "application/json", "User-Agent": "profile-stats" },
  body: JSON.stringify({ query, variables: { login: LOGIN } }),
});
const json = await res.json();
// Gagal berarti berhenti: lebih baik gambar lama bertahan daripada menimpanya dengan kartu kosong.
if (!res.ok || json.errors || !json.data?.user) throw new Error("GraphQL gagal: " + JSON.stringify(json.errors ?? res.status));

const u = json.data.user, cc = u.contributionsCollection;
const weeks = cc.contributionCalendar.weeks;
// Markup dan template tidak dihitung: yang ingin ditunjukkan adalah bahasa pemrograman.
const SKIP = new Set(["HTML", "CSS", "SCSS", "Blade", "Dockerfile", "Shell"]);
const langs = {};
for (const r of u.repositories.nodes) for (const e of r.languages.edges) if (!SKIP.has(e.node.name))
  (langs[e.node.name] ??= { size: 0, color: e.node.color || "#8b949e" }).size += e.size;
const total = Object.values(langs).reduce((a, l) => a + l.size, 0);
const top = Object.entries(langs).sort((a, b) => b[1].size - a[1].size).slice(0, 6);

const max = Math.max(1, ...weeks.flatMap((w) => w.contributionDays.map((d) => d.contributionCount)));
const level = (c) => (c === 0 ? 0 : Math.min(4, 1 + Math.floor((c / max) * 3.999)));
const fmt = (n) => n.toLocaleString("en-US");

const tiles = [
  [fmt(cc.contributionCalendar.totalContributions), "contributions, last year"],
  [fmt(cc.totalCommitContributions), "commits"],
  [fmt(cc.totalPullRequestContributions), "pull requests"],
  [fmt(u.repositories.totalCount), "public repos"],
];

function render(name) {
  const t = themes[name];
  const ramp = [t.grid === t.card ? t.line : t.line, name === "dark" ? "#2b3167" : "#c7cbff", name === "dark" ? "#4a52b8" : "#8e97f5", name === "dark" ? "#6b75e8" : "#6a6cf0", t.accent];
  const tileSvg = tiles.map(([v, l], i) => {
    const x = 32 + i * 226;
    return `<g style="animation:appear .5s ${(i * 0.1).toFixed(1)}s ease-out both"><text class="m" x="${x}" y="52" font-size="30" font-weight="700" fill="${t.fg}">${esc(v)}</text><text class="m" x="${x}" y="74" font-size="11" fill="${t.muted}">${esc(l)}</text></g>`;
  }).join("");

  const cell = 13, gap = 3, x0 = 32, y0 = 108;
  const grid = weeks.map((w, c) => w.contributionDays.map((d, r) =>
    `<rect x="${x0 + c * (cell + gap)}" y="${y0 + r * (cell + gap)}" width="${cell}" height="${cell}" rx="3" fill="${ramp[level(d.contributionCount)]}" style="animation:appear .4s ${(0.4 + c * 0.025).toFixed(2)}s ease-out both"/>`
  ).join("")).join("");

  let bx = 32; const bw = 896;
  const segs = top.map(([n, l]) => { const w = Math.max(4, (l.size / total) * bw), s = `<rect x="${bx}" y="262" width="${w.toFixed(1)}" height="10" fill="${l.color}"/>`; bx += w; return s; }).join("");
  let lx = 32;
  const legend = top.map(([n, l]) => { const s = `<circle cx="${lx + 4}" cy="297" r="4" fill="${l.color}"/><text class="m" x="${lx + 14}" y="301" font-size="11" fill="${t.muted}">${esc(n)} ${((l.size / total) * 100).toFixed(0)}%</text>`; lx += 24 + (n.length + 4) * 6.8; return s; }).join("");

  const body = `
<rect x=".5" y=".5" width="959" height="339" rx="14" fill="${t.card}" stroke="${t.line}"/>
${tileSvg}
${grid}
<text class="m" x="32" y="248" font-size="11" fill="${t.muted}">languages across public repos</text>
<clipPath id="r"><rect x="32" y="262" width="${bw}" height="10" rx="5"/></clipPath><g clip-path="url(#r)">${segs}</g>
${legend}
<text class="m" x="928" y="325" font-size="10" fill="${t.muted}" text-anchor="end" opacity=".7">updated ${new Date().toISOString().slice(0, 10)} · generated by scripts/stats.mjs</text>`;
  return svg(960, 340, t, `<title>GitHub activity of ${esc(LOGIN)}: contributions, repos and languages</title>${body}`);
}

for (const n of ["dark", "light"]) writeFileSync(`assets/stats-${n}.svg`, render(n));
console.log("stats dibuat:", tiles.map((t) => t.join(" ")).join(" | "), "|", top.map(([n]) => n).join(","));
